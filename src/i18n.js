class I18nManager {
  constructor() {
    let savedLang = 'vi';
    try {
      savedLang = localStorage.getItem('3d2048_lang') || 'vi';
    } catch {}
    this.currentLang = DICTIONARY[savedLang] ? savedLang : 'vi';
  }

  getLanguage() {
    return this.currentLang;
  }

  t(key, fallback = '') {
    const dict = DICTIONARY[this.currentLang] || DICTIONARY.vi;
    if (dict && dict[key] !== undefined) {
      return dict[key];
    }
    const defaultDict = DICTIONARY.vi;
    if (defaultDict && defaultDict[key] !== undefined) {
      return defaultDict[key];
    }
    return fallback || key;
  }

  setLanguage(lang) {
    if (!DICTIONARY[lang]) return;
    this.currentLang = lang;
    try {
      localStorage.setItem('3d2048_lang', lang);
    } catch {}

    this.applyToDOM();
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  applyToDOM() {
    // 0. Rich HTML elements (Formatted tips with kbd, gesture pills, etc.)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const val = this.t(key);
      if (val !== undefined && val !== '') {
        el.innerHTML = val;
      }
    });

    // 1. Text elements (Preserve SVG icons inside buttons & complex components)
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val !== undefined && val !== '') {
        const isInteractive = el.tagName === 'BUTTON' || el.classList.contains('glass-btn') || el.classList.contains('dpad-layer-btn');
        const textSpan = el.querySelector('.btn-text');
        if (textSpan) {
          textSpan.textContent = val;
        } else if (isInteractive && el.querySelector('span')) {
          el.querySelector('span').textContent = val;
        } else if (el.querySelector('svg')) {
          let updated = false;
          el.childNodes.forEach(n => {
            if (n.nodeType === Node.TEXT_NODE && n.textContent.trim().length > 0) {
              n.textContent = ' ' + val;
              updated = true;
            }
          });
          if (!updated) {
            const span = document.createElement('span');
            span.textContent = ' ' + val;
            el.appendChild(span);
          }
        } else {
          el.textContent = val;
        }
      }
    });

    // 2. Titles
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = this.t(key);
      if (val) el.title = val;
    });

    // 3. Optgroup labels
    document.querySelectorAll('optgroup[data-i18n-label]').forEach(el => {
      const key = el.getAttribute('data-i18n-label');
      const val = this.t(key);
      if (val) el.label = val;
    });

    // 4. Update html lang attribute
    document.documentElement.lang = this.currentLang;
  }
}

export const i18n = new I18nManager();
export const t = (key, fallback) => i18n.t(key, fallback);
export const setLanguage = (lang) => i18n.setLanguage(lang);
export const getCurrentLanguage = () => i18n.getLanguage();
